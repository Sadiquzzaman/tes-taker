import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const ttfPath = path.join(root, "public/fonts/NotoSansBengali-Regular.ttf");
const outPath = path.join(root, "utils/exam/pdf/notoSansBengaliFontData.ts");

const base64 = fs.readFileSync(ttfPath).toString("base64");
const content = `// Auto-generated by scripts/generate-bengali-font-module.mjs — do not edit manually
export const NOTO_SANS_BENGALI_TTF_BASE64 = ${JSON.stringify(base64)};
`;

fs.writeFileSync(outPath, content);
console.log(`Generated ${outPath} (${fs.statSync(outPath).size} bytes)`);
